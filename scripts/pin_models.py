"""Developer tool: regenerate app/models/catalog.toml with pinned revisions and SHA-256s.

Usage:  uv run python scripts/pin_models.py

For each repo it resolves the current commit hash, then lists the files at that commit.
Large (LFS) files come with a SHA-256 in Hugging Face's metadata. Small files are
downloaded here, hashed, and cross-checked against their git blob hash, so every
file in the catalog has a SHA-256 that the app verifies after download.

This only contacts huggingface.co; the app itself never runs this script.
"""

from __future__ import annotations

import hashlib
import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

HF = "https://huggingface.co"
OUT = Path(__file__).resolve().parents[1] / "app" / "models" / "catalog.toml"

# logical model -> (label, {backend: repo})
MODELS: dict[str, tuple[str, dict[str, str]]] = {
    "tiny": ("Tiny", {
        "faster-whisper": "Systran/faster-whisper-tiny",
        "openvino": "OpenVINO/whisper-tiny-fp16-ov",
    }),
    "base": ("Base", {
        "faster-whisper": "Systran/faster-whisper-base",
        "openvino": "OpenVINO/whisper-base-fp16-ov",
    }),
    "small": ("Small", {
        "faster-whisper": "Systran/faster-whisper-small",
        "openvino": "OpenVINO/whisper-small-fp16-ov",
    }),
    "medium": ("Medium", {
        "faster-whisper": "Systran/faster-whisper-medium",
        "openvino": "OpenVINO/whisper-medium-int8-ov",
    }),
    "large-v3-turbo": ("Large v3 Turbo", {
        "faster-whisper": "dropbox-dash/faster-whisper-large-v3-turbo",
        "openvino": "OpenVINO/whisper-large-v3-turbo-int8-ov",
    }),
}

SKIP = {".gitattributes", "README.md"}


def _get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "crowe-vibe-whisper-pin"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def _git_blob_sha1(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def pin(repo: str) -> dict:
    info = json.loads(_get(f"{HF}/api/models/{repo}/revision/main"))
    revision = info["sha"]
    tree = json.loads(_get(f"{HF}/api/models/{repo}/tree/{revision}?recursive=true"))
    files = []
    for entry in tree:
        path = entry["path"]
        if entry["type"] != "file" or path in SKIP or path.startswith(".") or path.endswith(".md"):
            continue
        lfs = entry.get("lfs")
        if lfs:
            sha256 = lfs["oid"]
        else:
            quoted = urllib.parse.quote(entry["path"])
            data = _get(f"{HF}/{repo}/resolve/{revision}/{quoted}")
            if _git_blob_sha1(data) != entry["oid"]:
                sys.exit(f"{repo}/{entry['path']}: git hash mismatch, refusing to pin")
            sha256 = hashlib.sha256(data).hexdigest()
        files.append({"path": entry["path"], "size": entry["size"], "sha256": sha256})
    return {"repo": repo, "revision": revision, "files": files}


def main() -> None:
    lines = [
        "# Generated by scripts/pin_models.py. Do not edit by hand.",
        "# Each file is verified against its SHA-256 after download.",
        "",
    ]
    for name, (label, variants) in MODELS.items():
        lines += [f'[models."{name}"]', f'label = "{label}"', ""]
        for backend, repo in variants.items():
            pinned = pin(repo)
            total = sum(f["size"] for f in pinned["files"])
            print(f"{name:16} {backend:15} {repo} @ {pinned['revision'][:10]} {total / 1e6:.0f} MB")
            lines += [
                f'[models."{name}".backends."{backend}"]',
                f'repo = "{pinned["repo"]}"',
                f'revision = "{pinned["revision"]}"',
                "files = [",
            ]
            for f in pinned["files"]:
                lines.append(f'  {{ path = "{f["path"]}", size = {f["size"]}, sha256 = "{f["sha256"]}" }},')
            lines += ["]", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
